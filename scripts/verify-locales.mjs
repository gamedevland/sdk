import assert from 'node:assert/strict';
import { ConfigStore, LocaleCatalog, LocalesService } from '../packages/engine/dist/sdk.js';
const codes = ['en','ru','es','pt-BR','de','fr','it','tr','zh-CN','ja','ko'];
for (const [hint, expected] of [['PT_br','pt-BR'],['pt-PT','pt-BR'],['zh-Hans-CN','zh-CN'],['zh-TW','zh-CN'],['es-MX','es'],['ru_RU','ru'],['xx',null]]) assert.equal(LocaleCatalog.normalize(hint), expected);
const configs = new ConfigStore();
for (const code of codes) configs.set(LocaleCatalog.getConfigId(code), { greeting: `${code}:{count}`, ...(code === 'en' ? { fallback: 'English' } : {}) });
const data = new Map();
const storage = { getItem: key => data.get(key) ?? null, setItem: (key,value) => data.set(key,value), removeItem: key => data.delete(key) };
const options = { supportedLocales: codes, storage, storageKey: 'language', preferredLocales: ['pl-PL','de-DE','fr-FR'] };
const service = new LocalesService(configs);
service.initialize(options);
assert.equal(service.getLang(), 'de');
assert.equal(data.size, 0, 'Auto-detection must not create a manual preference');
assert.equal(service.t('greeting',{count:3}), 'de:3');
assert.equal(service.t('fallback'), 'English');
let changes = 0;
const off = service.subscribe(() => changes++);
service.setLang('ja-JP');
assert.equal(data.get('language'), 'ja');
assert.equal(changes, 1);
service.setLang('ja');
assert.equal(changes, 1);
assert.equal(service.getRevision(), 2);
off();
const next = new LocalesService(configs);
next.initialize({...options, deviceLocale:'ru'});
assert.equal(next.getLang(), 'ja', 'Saved choice must outrank device and browser');
data.clear();
next.initialize({...options, deviceLocale:'ko-KR'});
assert.equal(next.getLang(), 'ko');
next.setLang('ko');
assert.equal(data.get('language'), 'ko', 'Choosing the current auto-detected language must still persist');
next.initialize({supportedLocales:codes,preferredLocales:['pl','uk']});
assert.equal(next.getLang(), 'en');
next.initialize({...options,storage:{getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}},deviceLocale:'es-AR'});
assert.equal(next.getLang(), 'es');
next.setLang('fr');
assert.equal(next.getLang(), 'fr');
const legacy = new LocalesService(configs);
legacy.setLang('ja');
assert.equal(legacy.getLang(), 'en', 'Existing two-locale games must retain their supported subset');
assert.throws(() => next.initialize({supportedLocales:['ru']}), /Default locale/);
console.log('Locale preferences: aliases, precedence, persistence, fallback, events, blocked storage and compatibility passed.');
const { Text } = await import('../packages/engine/dist/renderers/pixi.js');
const view = {
  text: 'A long translated label', style: { fontSize: 20, lineHeight: 0 },
  getLocalBounds() { return { width: Math.ceil(this.style.fontSize * this.text.length * .6), height: Math.ceil(this.style.fontSize * 1.4) + 1 }; },
};
const node = new Text(view);
node.fitTo(100, 12);
assert(view.getLocalBounds().width <= 100);
assert(view.getLocalBounds().height <= 12, 'Fitting must account for quantized font metrics');
const fitted = view.style.fontSize;
node.fitTo(100,12);
assert.equal(view.style.fontSize,fitted, 'Fitting must be idempotent');
assert.throws(() => node.fitTo(0), /positive/);
console.log('Text fitting: quantized metrics, bounded font search, idempotency and invalid bounds passed.');
